// Filter layer 1 (structural): the path gate, the content gate's size window and rejections, and the
// comment-to-code ratio / tests bonus in ScoreCodeQuality.

import { test, expect } from "bun:test";
import { CodeContentVerdict, DefaultFileFilter, IsCodeLang, IsSubstantiveCodeContent, IsSubstantiveCodePath } from "../Foundry/CodeFileFilter.ts";
import { ScoreCodeQuality, CommentBand } from "../Brain/Data/QualityFilter.ts";
import { CommentLineRatio, DataLineFraction, ImportLineFraction, ScanSource, StringLiteralFraction } from "../Brain/Data/EducationalFeatures.ts";

// A small, real, documented module (~600 B) — passes every content check.
const Module = `import { readFileSync } from "node:fs";

/** Parse a KEY=VALUE env file into a map (blank lines and # comments are skipped). */
export function ParseEnvFile(Path: string): Map<string, string> {
  const Out = new Map<string, string>();
  for (const Raw of readFileSync(Path, "utf8").split("\\n")) {
    const Line = Raw.trim();
    if (Line === "" || Line.startsWith("#")) continue;
    const Eq = Line.indexOf("=");
    // A line without "=" is malformed: skip it rather than guessing.
    if (Eq <= 0) continue;
    Out.set(Line.slice(0, Eq).trim(), Line.slice(Eq + 1).trim());
  }
  return Out;
}
`;

function Repeat(Line: (I: number) => string, Count: number): string {
  return Array.from({ length: Count }, (_V, I) => Line(I)).join("\n");
}

test("size window: default 200 B … 50 KB, overridable per caller", () => {
  expect(DefaultFileFilter).toEqual({ MinBytes: 200, MaxBytes: 50 * 1024 });
  expect(IsSubstantiveCodeContent(Module)).toBe(true);
  const Small = "export function Id(X: number): number {\n  return X;\n}\n";
  expect(CodeContentVerdict(Small).Reason).toMatch(/^too small/);
  expect(IsSubstantiveCodeContent(Small, { MinBytes: 40 })).toBe(true); // the spec ingest's own bounds
  const Big = `${Module}\n${Repeat((I) => `export function F${I}(Value: number): number {\n  return Value * ${I} + 1;\n}`, 1400)}\n`;
  expect(Buffer.byteLength(Big)).toBeGreaterThan(DefaultFileFilter.MaxBytes);
  expect(CodeContentVerdict(Big).Reason).toMatch(/^too large/);
  expect(IsSubstantiveCodeContent(Big, { MaxBytes: 512_000 })).toBe(true);
  expect(IsSubstantiveCodeContent(Big, 512_000)).toBe(true); // legacy numeric MaxBytes still works
});

test("imports-only files (barrels / re-export hubs) are rejected", () => {
  const Barrel = `// Public surface of the parser package.\n${Repeat((I) => `export { Parser${I}, type Options${I} } from "./Parser${I}.ts";`, 10)}\nimport {\n  Lexer,\n  Token,\n} from "./Lexer.ts";\nexport const Version = "1.0";\n`;
  expect(ImportLineFraction(ScanSource(Barrel))).toBeGreaterThanOrEqual(0.8);
  expect(CodeContentVerdict(Barrel).Reason).toMatch(/^imports only/);
  expect(ImportLineFraction(ScanSource(Module))).toBeLessThan(0.2);
});

test("lockfiles, snapshots, i18n/locale files and generated code are rejected by path", () => {
  for (const Path of ["package-lock.json", "yarn.lock", "web/pnpm-lock.yaml", "bun.lockb", "Cargo.lock", "go.sum"]) expect(IsSubstantiveCodePath(Path)).toBe(false);
  expect(IsSubstantiveCodePath("src/__snapshots__/View.ts.snap")).toBe(false);
  expect(IsSubstantiveCodePath("src/View.ts.snap")).toBe(false);
  for (const Path of ["src/i18n/en.json", "src/locales/fr.ts", "src/messages.fr.ts", "app/strings.i18n.ts", "src/lang/pt-BR.js", "src/en.json"]) {
    expect({ Path, Kept: IsSubstantiveCodePath(Path) }).toEqual({ Path, Kept: false });
  }
  for (const Path of ["api/user_pb2.py", "pkg/zz_generated.deepcopy.go", "pkg/types_gen.go", "lib/model.g.dart", "src/api.generated.ts"]) {
    expect({ Path, Kept: IsSubstantiveCodePath(Path) }).toEqual({ Path, Kept: false });
  }
  // Two-letter code files that are NOT locales stay in.
  for (const Path of ["src/go.ts", "src/io.ts", "pkg/db.go", "src/types.mts"]) expect({ Path, Kept: IsSubstantiveCodePath(Path) }).toEqual({ Path, Kept: true });
  expect(CodeContentVerdict(`// Code generated by protoc-gen-go. DO NOT EDIT.\n${Module}`).Reason).toBe("generated-file banner");
});

test("extension allowlist can be narrowed to some languages", () => {
  const Web = { Langs: ["typescript", "javascript", "html", "css", "go", "sql"] };
  expect(IsSubstantiveCodePath("src/App.tsx", Web)).toBe(true);
  expect(IsSubstantiveCodePath("db/schema.sql", Web)).toBe(true);
  expect(IsSubstantiveCodePath("src/main.py", Web)).toBe(false);
  expect(IsSubstantiveCodePath("src/main.py")).toBe(true); // default: every known language
  expect(IsSubstantiveCodePath("README.md")).toBe(false);
  expect(IsCodeLang("typescript") && IsCodeLang("ts") && IsCodeLang("go")).toBe(true);
  expect(IsCodeLang("text-ar") || IsCodeLang("unknown")).toBe(false);
});

test("i18n JSON-like tables and >90% string-literal files are rejected by content", () => {
  const Translations = `export default {\n${Repeat((I) => `  "screen.title.${I}": "Willkommen auf der Startseite Nummer ${I}",`, 30)}\n};\n`;
  const Scan = ScanSource(Translations);
  expect(StringLiteralFraction(Scan)).toBeGreaterThan(0.9);
  expect(CodeContentVerdict(Translations).Reason).toMatch(/^string literals/);

  const RowTable = `export const Users = [\n${Repeat((I) => `  { id: ${I}, name: "U${I}", active: true, score: ${I}.5, team: null },`, 40)}\n];\n`;
  expect(DataLineFraction(ScanSource(RowTable))).toBeGreaterThan(0.9);
  expect(CodeContentVerdict(RowTable).Reason).toMatch(/^data table/);
  const NumberTable = `export const Primes = [\n${Repeat((I) => `  [${I}, ${I * 7}, ${I * 13}, ${I * 31}, ${I * 101}],`, 40)}\n];\n`;
  expect(IsSubstantiveCodeContent(NumberTable)).toBe(false); // digits-only: caught as symbol soup / data
  expect(DataLineFraction(ScanSource(NumberTable))).toBeGreaterThan(0.9);
  expect(DataLineFraction(ScanSource(Module))).toBeLessThan(0.2);
  expect(StringLiteralFraction(ScanSource(Module))).toBeLessThan(0.3);
});

test("no declaration, comments only, minified and blobs are rejected; markup and SQL pass", () => {
  const CallsOnly = `${Repeat((I) => `Register(Handlers.Item${I}, Options.Default);`, 12)}\n`;
  expect(CodeContentVerdict(CallsOnly).Reason).toBe("no function/class/const declaration");
  const LicenseOnly = `/*\n${Repeat(() => " * Licensed under the Apache License, Version 2.0 (the License).", 8)}\n */\n`;
  expect(CodeContentVerdict(LicenseOnly).Reason).toMatch(/^comments only/);
  const Minified = `var a=function(b,c){return b+c},d=function(e){for(var f=0,g=0;g<e.length;g++)f+=e[g];return f};`.repeat(20);
  expect(CodeContentVerdict(Minified).Reason).toMatch(/^minified/);
  expect(CodeContentVerdict(`${Module}\nconst Icon = "data:image/png;base64,AAAA";\n`).Reason).toMatch(/blob/);

  const Css = `/* Card component: a padded flex column with a title and a muted variant. */\n.card {\n  display: flex;\n  padding: 16px;\n  border-radius: 8px;\n}\n\n.card__title {\n  font-size: 1.25rem;\n  font-weight: 600;\n}\n\n.card--muted {\n  opacity: 0.6;\n  color: #555555;\n}\n\n.card__body {\n  line-height: 1.5;\n  overflow-wrap: anywhere;\n}\n`;
  expect(CodeContentVerdict(Css)).toEqual({ Passed: true, Reason: null });
  const Sql = `-- Users of the app; email is the login and must be unique.\nCREATE TABLE users (\n  id BIGSERIAL PRIMARY KEY,\n  email TEXT NOT NULL UNIQUE,\n  created_at TIMESTAMPTZ NOT NULL DEFAULT now()\n);\n\nCREATE INDEX users_email_idx ON users (email);\n\nSELECT email, created_at FROM users WHERE created_at > now() - interval '7 days' ORDER BY created_at DESC;\n`;
  expect(CodeContentVerdict(Sql)).toEqual({ Passed: true, Reason: null });
});

test("the scanner separates comments, strings and code without being fooled by quotes in comments", () => {
  const Text = `// don't open a string here\nconst A = "x // not a comment";\n# shell-style note\nconst B = 1; /* block\n * still block\n */\nconst C = '#fff';\n`;
  const Scan = ScanSource(Text);
  expect(Scan.CommentLines).toBe(4); // line 1, line 3, and the two block-only lines
  expect(Scan.CodeLines).toBe(3); // A, B (a trailing block opener does not make it a comment line), C
  expect(Scan.CodeLineTexts[1]).toBe('const A = "";');
  expect(Scan.CodeLineTexts[6]).toBe("const C = '';"); // '#fff' is a string, not a # comment
  expect(CommentLineRatio(Scan)).toBeCloseTo(4 / 7, 6);
  const Py = `def Mean(Values):\n    """Arithmetic mean."""\n    return sum(Values) / len(Values)\n`;
  const PyScan = ScanSource(Py);
  expect(PyScan.DocComments).toBe(1);
  expect(PyScan.CommentLines).toBe(1);
});

test("comment-to-code ratio: the 5–30% band scores higher than 0% and >60%", () => {
  const Body = Repeat((I) => `export function Step${I}(Value: number): number {\n  return Value + ${I};\n}`, 6);
  const Bare = `${Body}\n`;
  const Banded = `// Step functions used by the pipeline.\n${Body}\n// Keep Step order stable: callers index by position.\n`;
  const Heavy = `${Repeat((I) => `// Old implementation line ${I}: return Value * ${I};`, 60)}\n${Body}\n`;
  const BareQ = ScoreCodeQuality(Bare);
  const BandedQ = ScoreCodeQuality(Banded);
  const HeavyQ = ScoreCodeQuality(Heavy);
  const Ratio = CommentLineRatio(ScanSource(Banded));
  expect(Ratio).toBeGreaterThanOrEqual(CommentBand.Low);
  expect(Ratio).toBeLessThanOrEqual(CommentBand.High);
  expect(BandedQ.Score).toBeGreaterThan(BareQ.Score);
  expect(BandedQ.Score).toBeGreaterThan(HeavyQ.Score);
  expect(BareQ.Reasons.join(";")).toContain("no comments");
  expect(HeavyQ.Reasons.join(";")).toContain("mostly comments");
  expect(BandedQ.Reasons.some((R) => R.startsWith("comment ratio"))).toBe(false);
  expect(BareQ.Passed && BandedQ.Passed).toBe(true); // a soft signal, not a gate on its own
});

test("tests or examples earn a bonus that offsets the comment penalty, never above 1", () => {
  const Bare = "export function Add(A: number, B: number): number {\n  return A + B;\n}\n";
  const WithTest = `${Bare}\ntest("Add", () => {\n  expect(Add(1, 2)).toBe(3);\n});\n`;
  const Q = ScoreCodeQuality(WithTest);
  expect(Q.Score).toBeGreaterThan(ScoreCodeQuality(Bare).Score);
  expect(Q.Score).toBeLessThanOrEqual(1);
  expect(Q.Reasons.join(";")).toContain("has tests or examples");
  // The bonus never rescues binary junk.
  let Binary = "";
  for (let I = 0; I < 200; I++) Binary += String.fromCharCode(I);
  expect(ScoreCodeQuality(`${Binary}\nexpect(1)`).Passed).toBe(false);
});

test("prose documents (README/guides) skip the code-structure checks; code never does", () => {
  const Readme = `# Parser\n\nA tiny, fast parser for configuration files, written in TypeScript.\n\n## Usage\n\nInstall it from [npm](https://www.npmjs.com/) and call it with the file contents:\n\n\`\`\`ts\nParse(Text);\n\`\`\`\n\nIt doesn't need any runtime dependencies and works in every modern browser and server.\n`;
  expect(CodeContentVerdict(Readme)).toEqual({ Passed: true, Reason: null }); // auto-detected markdown
  expect(CodeContentVerdict(Readme, { Lang: "markdown" })).toEqual({ Passed: true, Reason: null });
  expect(CodeContentVerdict(Readme, { Lang: "typescript" }).Passed).toBe(false); // caller says it is code
  const Paragraphs = `${"This guide explains how the parser reads a file and why every step exists in this order. ".repeat(8)}\n\n`.repeat(3);
  expect(CodeContentVerdict(Paragraphs)).toEqual({ Passed: true, Reason: null }); // long lines are not "minified" prose
  // Python's "# comment" lines are not markdown headings: a commented barrel is still imports-only.
  const PyBarrel = `# Public API.\n# Re-exported for convenience.\n${Array.from({ length: 12 }, (_V, I) => `from .module${I} import Thing${I}, Other${I}`).join("\n")}\n`;
  expect(CodeContentVerdict(PyBarrel).Reason).toMatch(/^imports only/);
});
